"""Generate web/static/house-legacy.css: every style.css rule that hardcodes a colour gets a body.ds override
mapped onto house tokens (light mode only). Re-run after editing style.css:  python3 tools/gen_house_legacy.py"""
import re, colorsys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
css = (ROOT / "web/static/style.css").read_text()
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

COLOR = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b")
def parse(c):
    c = c.strip().lower()
    if c == "white": return (255, 255, 255, 1)
    if c == "black": return (0, 0, 0, 1)
    if c.startswith("#"):
        h = c[1:]
        if len(h) in (3, 4): h = "".join(x * 2 for x in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return (r, g, b, a)
    n = [float(x) for x in re.findall(r"[\d.]+", c)]
    return (n[0], n[1], n[2], n[3] if len(n) > 3 else 1)
def kind(c):
    r, g, b, a = parse(c)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    hue = h * 360
    if s < 0.18 or l < 0.06 or l > 0.95:
        return ("light" if l > 0.6 else "dark"), a
    if 25 <= hue < 65: return "amber", a
    if hue < 25 or hue >= 340: return "red", a
    if 65 <= hue < 170: return "green", a
    return "accent", a   # blues, purples, pinks: the old accent family
def map_decl(prop, val, rule_has_solid_bg):
    cols = COLOR.findall(val)
    if not cols or "var(" in val and not cols: return None
    k, a = kind(cols[0])
    if prop == "color" or prop == "-webkit-text-fill-color":
        if rule_has_solid_bg: return "var(--content-on-accent)"
        return {"amber": "var(--attention)", "red": "var(--critical)", "green": "var(--accent)", "accent": "var(--accent)"}.get(k, "var(--ink)")
    if prop in ("background", "background-color"):
        if "gradient" in val:
            return "var(--accent)" if k in ("accent", "red", "green") and a > .5 else "var(--bg-sunken)"
        if k in ("dark", "light"): return "var(--bg-sunken)" if a > .02 else None
        if a < .5: return {"amber": "rgba(188,126,46,.12)", "red": "rgba(168,70,51,.1)"}.get(k, "var(--accent-tint)")
        return {"amber": "var(--attention)", "red": "var(--critical)"}.get(k, "var(--accent)")
    if prop.startswith("border") and "radius" not in prop:
        return re.sub(COLOR, "var(--line-strong)" if k in ("dark", "light") else ("var(--accent-line)" if k in ("accent", "green") else "var(--line-strong)"), val)
    if prop in ("box-shadow", "text-shadow", "filter"):
        return "none" if prop != "box-shadow" else "var(--elev-1)"
    if prop in ("outline", "outline-color", "fill", "stroke", "accent-color", "caret-color", "stop-color"):
        return re.sub(COLOR, "var(--accent)" if k not in ("amber", "red") else ("var(--attention)" if k == "amber" else "var(--critical)"), val)
    return None

out = ["/* GENERATED by tools/gen_house_legacy.py from style.css. Do not edit by hand. Loads after style.css, before house.css. */"]
def walk(text, wrap=None):
    i = 0
    while i < len(text):
        j = text.find("{", i)
        if j < 0: break
        head = text[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < len(text):
            depth += {"{": 1, "}": -1}.get(text[k], 0); k += 1
        body = text[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            walk(body, head)
        elif not head.startswith("@"):
            decls = [d.split(":", 1) for d in body.split(";") if ":" in d]
            decls = [(p.strip().lower(), v.strip()) for p, v in decls]
            solid = any(p in ("background", "background-color") and COLOR.search(v) and kind(COLOR.findall(v)[0])[0] in ("accent", "red", "green") and kind(COLOR.findall(v)[0])[1] > .5 for p, v in decls)
            new = []
            # Text floor (SIZING.md): any size under 12 px takes the meta step, which never goes under 13.
            for p, v in decls:
                fm = re.match(r"([\d.]+)(rem|px|em)", v) if p == "font-size" else None
                if fm and (float(fm.group(1)) * (16 if fm.group(2) in ("rem", "em") else 1)) < 12:
                    new.append("font-size: var(--fs-meta, 0.8125rem)" + (" !important" if "!important" in v else ""))
            for p, v in decls:
                if not COLOR.search(v): continue
                m = map_decl(p, v.replace("!important", "").strip(), solid)
                if m: new.append(f"{p}: {m}" + (" !important" if "!important" in v else ""))
            if new:
                sels = []
                pass
                for s in head.split(","):
                    s = s.strip()
                    if not s or re.match(r"^(html|body|:root)\b", s) or s.startswith("@") or "%" in s or s in ("from", "to"): continue
                    sels.append("body.ds " + s)
                if sels:
                    rule = ", ".join(sels) + " { " + "; ".join(new) + "; }"
                    out.append(f"{wrap} {{ {rule} }}" if wrap else rule)
        i = k
walk(css)
(ROOT / "web/static/house-legacy.css").write_text("\n".join(out) + "\n")
print(len(out) - 1, "rules")
